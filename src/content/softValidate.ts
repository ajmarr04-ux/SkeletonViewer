// Validation of the soft-tissue content (musculoskeletal spec §10; M8 plan
// decisions 1 to 10) as pure functions, so each rule can be tested on small
// fixtures. scripts/validate-content.ts reads the files and prints the result.

import type { ZodError } from "zod";
import { mirrorFile, splitFrontMatter } from "./frontmatter";
import { wordCount } from "./schema";
import {
  LAYER_FOLDERS,
  SOFT_BODY_WORDS,
  jointsSchema,
  movementsSchema,
  muscleHierarchySchema,
  schemaForKind,
  type Attachment,
  type CartilageFm,
  type LigamentFm,
  type MuscleFm,
  type MuscleHierarchyNode,
  type MusclePartFm,
  type SoftFm,
  type SoftLayer,
} from "./softSchema";

/** An entry of content/soft-ids.json (generated by `npm run soft-ids`). */
export type SoftIdEntry = {
  id: string;
  name: string;
  latin: string | null;
  kind: string;
  layer: SoftLayer;
  side: "left" | "right" | "midline";
  group: string[];
  meshAvailable: boolean;
  parent?: string | null;
  partType?: string;
  parts?: string[];
  alsoServes?: string[];
  inconstant?: boolean;
};

export type SoftContentInput = {
  softIds: SoftIdEntry[];
  /** Bone and tooth IDs (content/ids.json). */
  boneIds: string[];
  /** Bone ID → its landmark IDs, from the bone content files. */
  boneLandmarks: Map<string, ReadonlySet<string>>;
  /** Content files by folder, then by file name without `.md`. */
  files: Record<SoftLayer, Map<string, string>>;
  /** Node names per model file stem (e.g. "muscles-high"). */
  meshes: Record<string, string[]>;
  /** content/articulations.json (already validated with the bones). */
  articulations: { joint: string }[];
  joints: unknown;
  movements: unknown;
  muscleHierarchy: unknown;
  /** The opposite side's ID for a bone or soft-tissue ID, else null. */
  opposite: (id: string) => string | null;
  /** content/QUESTIONS.md, for the synergistOverrides rule. */
  questions: string;
};
export type SoftContentOptions = {
  /** Plan decision 10: missing files (and the rules that need them) are counted, not failed. */
  allowMissingSoft?: boolean;
};
export type SoftContentReport = {
  errors: string[];
  warnings: string[];
  /** Files present, and how many the table expects. */
  files: number;
  expected: number;
  /** Parsed front matter by ID (valid files only). */
  parsed: Map<string, SoftFm>;
};

/** Ligaments that may have `joint: null` (plan decision 3), without side. */
export const LIGAMENT_NO_JOINT = new Set([
  "inguinal_ligament",
  "interosseous_membrane_leg",
  "interosseous_membrane_forearm",
  "obturator_membrane",
  "sacrospinous_ligament",
  "sacrotuberous_ligament",
  "superior_transverse_scapular_ligament",
  "inferior_transverse_scapular_ligament",
  "coraco_acromial_ligament",
  "stylohyoid_ligament",
  "pterygospinous_ligament",
  "sphenomandibular_ligament",
  "nuchal_ligament",
  "external_intercostal_membrane",
  "internal_intercostal_membrane",
]);
/** Cartilage that may have `joint: null` (spec §4.5, plan decision 3). */
export const CARTILAGE_NO_JOINT = new Set(["costal_cartilage_8", "costal_cartilage_9", "costal_cartilage_10"]);

const sideFree = (id: string) => id.replace(/_(left|right)$/, "");
const zodLines = (where: string, e: ZodError): string[] =>
  e.issues.map((i) => `${where}${i.path.length ? ` ${i.path.join(".")}` : ""}: ${i.message}`);
const sameSet = (a: readonly string[], b: readonly string[]) => a.length === b.length && [...a].sort().join() === [...b].sort().join();

export function validateSoftContent(input: SoftContentInput, opts: SoftContentOptions = {}): SoftContentReport {
  const errors: string[] = [];
  const warnings: string[] = [];
  const parsed = new Map<string, SoftFm>();
  const soft = new Map(input.softIds.map((e) => [e.id, e]));
  const bones = new Set(input.boneIds);
  const known = (id: string) => soft.has(id) || bones.has(id);
  const allowMissing = !!opts.allowMissingSoft;

  // --- Vocabulary files ---
  const pairJoints = new Set(input.articulations.map((a) => a.joint));
  const functionalJoints = new Map<string, string[]>();
  const js = jointsSchema.safeParse(input.joints);
  if (!js.success) errors.push(...zodLines("joints.json", js.error));
  else {
    for (const j of js.data) {
      const where = `joints.json ${j.id}`;
      if (functionalJoints.has(j.id)) errors.push(`${where}: listed twice`);
      if (pairJoints.has(j.id)) errors.push(`${where}: already a joint ID in articulations.json`);
      functionalJoints.set(j.id, j.articulations);
      for (const m of j.articulations) if (!pairJoints.has(m)) errors.push(`${where}: ${m} is not a joint in articulations.json`);
      const dup = j.articulations.find((m, i) => j.articulations.indexOf(m) !== i);
      if (dup) errors.push(`${where}: ${dup} is listed twice`);
      const suffix = j.side === "midline" ? null : `_${j.side}`;
      if (suffix && !j.id.endsWith(suffix)) errors.push(`${where}: side ${j.side}, but the ID doesn't end in ${suffix}`);
      for (const m of j.articulations) {
        const wrong = j.side === "left" ? /_right$/ : j.side === "right" ? /_left$/ : /_(left|right)$/;
        if (wrong.test(m)) errors.push(`${where}: ${m} is on the wrong side for a ${j.side} joint`);
      }
    }
    for (const j of js.data) {
      if (j.side !== "left") continue;
      const twin = js.data.find((x) => x.id === j.id.replace(/_left$/, "_right"));
      if (!twin) errors.push(`joints.json ${j.id}: no right-side twin`);
      else if (twin.name !== j.name || !sameSet(twin.articulations, j.articulations.map((m) => m.replace(/_left$/, "_right"))))
        errors.push(`joints.json ${twin.id}: doesn't mirror ${j.id}`);
    }
    for (const j of js.data) if (j.side === "right" && !js.data.some((x) => x.id === j.id.replace(/_right$/, "_left"))) errors.push(`joints.json ${j.id}: no left-side twin`);
  }
  const isJoint = (id: string) => pairJoints.has(id) || functionalJoints.has(id);

  const mv = movementsSchema.safeParse(input.movements);
  const movements = new Set<string>();
  if (!mv.success) errors.push(...zodLines("movements.json", mv.error));
  else {
    for (const m of mv.data.movements) {
      if (movements.has(m)) errors.push(`movements.json: ${m} is listed twice`);
      movements.add(m);
    }
    for (const [a, b] of mv.data.antagonistPairs) {
      for (const m of [a, b]) if (!movements.has(m)) errors.push(`movements.json antagonistPairs: ${m} is not a movement`);
      if (a === b) errors.push(`movements.json antagonistPairs: ${a} can't oppose itself`);
    }
  }

  // --- Content files ---
  const expected = input.softIds.length;
  let present = 0;
  for (const layer of Object.keys(LAYER_FOLDERS) as SoftLayer[]) {
    for (const [name, text] of input.files[layer]) {
      present++;
      const where = `content/${LAYER_FOLDERS[layer]}/${name}.md`;
      const entry = soft.get(name);
      if (!entry) {
        errors.push(`${where}: no such ID in content/soft-ids.json`);
        continue;
      }
      if (entry.layer !== layer) errors.push(`${where}: ${name} is in the ${entry.layer} layer; move it to content/${LAYER_FOLDERS[entry.layer]}/`);
      let split;
      try {
        split = splitFrontMatter(text);
      } catch (e) {
        errors.push(`${where}: ${(e as Error).message}`);
        continue;
      }
      const schema = schemaForKind(entry.kind);
      if (!schema) {
        errors.push(`${where}: unknown kind ${entry.kind}`);
        continue;
      }
      const res = schema.safeParse(split.data);
      if (!res.success) {
        errors.push(...zodLines(where, res.error));
        continue;
      }
      const d = res.data;
      if (d.id !== name) errors.push(`${where}: id is ${d.id}, but the file is named ${name}`);
      if (d.kind !== entry.kind) errors.push(`${where}: kind is ${d.kind}; soft-ids.json says ${entry.kind}`);
      if (d.side !== entry.side) errors.push(`${where}: side is ${d.side}; soft-ids.json says ${entry.side}`);
      if (d.name !== entry.name) errors.push(`${where}: name is "${d.name}"; soft-ids.json says "${entry.name}"`);
      const words = wordCount(split.body);
      const range = SOFT_BODY_WORDS[entry.kind]!;
      if (words < range.min || words > range.max) errors.push(`${where}: summary is ${words} words (${range.min} to ${range.max} for ${entry.kind})`);
      parsed.set(name, d);
      errors.push(...checkEntry(where, d, entry));
    }
  }

  function checkRef(where: string, field: string, id: string, self: SoftIdEntry) {
    if (!known(id)) return [`${where}: ${field} ${id} doesn't exist`];
    if (self.side === "left" && id.endsWith("_right")) return [`${where}: ${field} ${id} is on the other side`];
    if (self.side === "right" && id.endsWith("_left")) return [`${where}: ${field} ${id} is on the other side`];
    return [];
  }
  function checkAttachments(where: string, field: string, list: Attachment[] | "inherit", self: SoftIdEntry): string[] {
    if (list === "inherit") return [];
    const out: string[] = [];
    list.forEach((a, i) => {
      if (!("structure" in a)) return;
      const f = `${field}[${i}]`;
      out.push(...checkRef(where, f, a.structure, self));
      if (a.structure === self.id) out.push(`${where}: ${f} attaches the structure to itself`);
      if (a.landmark !== undefined && known(a.structure)) {
        const lm = input.boneLandmarks.get(a.structure);
        if (!bones.has(a.structure)) out.push(`${where}: ${f} landmark ${a.landmark}: only bones have landmarks`);
        else if (!lm) out.push(`${where}: ${f} landmark ${a.landmark}: ${a.structure} has no content file`);
        else if (!lm.has(a.landmark)) out.push(`${where}: ${f} ${a.structure} has no landmark ${a.landmark} (add it to the bone file)`);
      }
    });
    return out;
  }
  function checkActions(where: string, d: MuscleFm | MusclePartFm, self: SoftIdEntry): string[] {
    const out: string[] = [];
    d.actions.forEach((a, i) => {
      const f = `actions[${i}]`;
      if (!isJoint(a.joint)) out.push(`${where}: ${f} joint ${a.joint} is in neither articulations.json nor joints.json`);
      else if ((self.side === "left" && a.joint.endsWith("_right")) || (self.side === "right" && a.joint.endsWith("_left")))
        out.push(`${where}: ${f} joint ${a.joint} is on the other side`);
      if (movements.size && !movements.has(a.movement)) out.push(`${where}: ${f} movement ${a.movement} is not in movements.json`);
    });
    const dup = d.actions.find((a, i) => d.actions.findIndex((b) => b.joint === a.joint && b.movement === a.movement) !== i);
    if (dup) out.push(`${where}: the action ${dup.joint} · ${dup.movement} is listed twice`);
    return out;
  }

  function checkEntry(where: string, d: SoftFm, e: SoftIdEntry): string[] {
    const out: string[] = [];
    if (d.kind === "muscle") {
      if (!sameSet(d.parts, e.parts ?? [])) out.push(`${where}: parts are [${d.parts.join(", ")}]; soft-ids.json says [${(e.parts ?? []).join(", ")}]`);
      out.push(...checkAttachments(where, "origin", d.origin, e), ...checkAttachments(where, "insertion", d.insertion, e), ...checkActions(where, d, e));
      if (d.actions.length === 0 && !d.functions) out.push(`${where}: actions is empty, so functions is required (spec §4.3)`);
      if (d.synergistOverrides) {
        for (const x of [...d.synergistOverrides.add, ...d.synergistOverrides.remove]) out.push(...checkRef(where, "synergistOverrides", x, e));
        const key = sideFree(d.id);
        const noted = input.questions.split("\n").some((l) => l.includes("synergistOverrides") && l.includes(key));
        if (!noted) out.push(`${where}: synergistOverrides needs a QUESTIONS.md entry naming synergistOverrides and ${key}`);
      }
    } else if (d.kind === "muscle_part") {
      if (d.parent !== (e.parent ?? null)) out.push(`${where}: parent is ${d.parent}; soft-ids.json says ${e.parent ?? null}`);
      if (d.partType !== e.partType) out.push(`${where}: partType is ${d.partType}; soft-ids.json says ${e.partType}`);
      if (!sameSet(d.alsoServes, e.alsoServes ?? [])) out.push(`${where}: alsoServes is [${d.alsoServes.join(", ")}]; soft-ids.json says [${(e.alsoServes ?? []).join(", ")}]`);
      if (d.parent !== null) {
        const p = soft.get(d.parent);
        if (!p || p.kind !== "muscle") out.push(`${where}: parent ${d.parent} is not a muscle`);
        else if (!(p.parts ?? []).includes(d.id)) out.push(`${where}: ${d.parent} doesn't list ${d.id} as a part`);
      } else {
        for (const f of ["origin", "insertion"] as const) if (d[f] === "inherit") out.push(`${where}: a part without a muscle can't inherit its ${f}`);
      }
      for (const x of d.alsoServes) if (soft.get(x)?.kind !== "muscle") out.push(`${where}: alsoServes ${x} is not a muscle`);
      out.push(...checkAttachments(where, "origin", d.origin, e), ...checkAttachments(where, "insertion", d.insertion, e), ...checkActions(where, d, e));
    } else if (d.kind === "ligament") {
      out.push(...checkJoint(where, d, LIGAMENT_NO_JOINT, e));
      d.connects.forEach((x, i) => out.push(...checkRef(where, `connects[${i}]`, x, e)));
    } else {
      out.push(...checkJoint(where, d, CARTILAGE_NO_JOINT, e));
      d.attachedTo.forEach((x, i) => out.push(...checkRef(where, `attachedTo[${i}]`, x, e)));
    }
    return out;
  }
  function checkJoint(where: string, d: LigamentFm | CartilageFm, allow: ReadonlySet<string>, e: SoftIdEntry): string[] {
    if (d.joint === null) return allow.has(sideFree(d.id)) ? [] : [`${where}: joint is null, but ${sideFree(d.id)} isn't on the no-joint list (plan decision 3)`];
    if (!isJoint(d.joint)) return [`${where}: joint ${d.joint} is in neither articulations.json nor joints.json`];
    if ((e.side === "left" && d.joint.endsWith("_right")) || (e.side === "right" && d.joint.endsWith("_left"))) return [`${where}: joint ${d.joint} is on the other side`];
    return [];
  }

  // --- Every muscle (with its parts) has an origin and an insertion (spec §10) ---
  let familiesSkipped = 0;
  for (const e of input.softIds) {
    const isFamily = e.kind === "muscle" || (e.kind === "muscle_part" && !e.parent);
    if (!isFamily) continue;
    const members = [e.id, ...(e.parts ?? [])];
    if (members.some((m) => !parsed.has(m))) {
      if (members.some((m) => parsed.has(m))) familiesSkipped++;
      continue;
    }
    const head = parsed.get(e.id) as MuscleFm | MusclePartFm;
    const parts = (e.parts ?? []).map((p) => parsed.get(p) as MusclePartFm);
    for (const f of ["origin", "insertion"] as const) {
      const own = head[f];
      const ok = (own !== "inherit" && own.length > 0) || parts.some((p) => p[f] !== "inherit" && p[f].length > 0);
      if (!ok) errors.push(`${e.id}: no ${f} on the muscle or any of its parts (spec §10)`);
      if (own !== "inherit" && own.length === 0) for (const p of parts) if (p[f] === "inherit") errors.push(`${p.id}: inherits the ${f} of ${e.id}, which is empty`);
    }
  }
  if (familiesSkipped && !allowMissing) errors.push(`${familiesSkipped} muscle(s) have some but not all of their part files`);

  // --- Mirrors ---
  for (const layer of Object.keys(LAYER_FOLDERS) as SoftLayer[]) {
    const files = input.files[layer];
    for (const [name, text] of files) {
      const e = soft.get(name);
      if (!e || e.side !== "right") continue;
      const left = input.opposite(name);
      const leftText = left ? files.get(left) : undefined;
      if (!left || leftText === undefined) {
        errors.push(`content/${LAYER_FOLDERS[layer]}/${name}.md: right-side file without its left-side file${left ? ` (${left}.md)` : ""}`);
        continue;
      }
      let want: string | null = null;
      try {
        want = mirrorFile(leftText, left, input.opposite);
      } catch {
        /* reported on the left file */
      }
      if (want !== null && want !== text)
        errors.push(`content/${LAYER_FOLDERS[layer]}/${name}.md: differs from the mirror of ${left}.md (edit the left file and run npm run content:mirror)`);
    }
  }

  // --- Missing files and meshes ---
  const hasFile = (e: SoftIdEntry) => input.files[e.layer].has(e.id);
  const missing = input.softIds.filter((e) => !hasFile(e));
  if (missing.length) {
    if (allowMissing) warnings.push(`${missing.length} of ${expected} soft-tissue structures have no content file yet (--allow-missing-soft)`);
    else errors.push(`${missing.length} soft-tissue structure(s) without a content file: ${missing.map((e) => e.id).join(", ")}`);
  }
  for (const [stem, names] of Object.entries(input.meshes)) {
    const layer = stem.replace(/-(high|low)$/, "") as SoftLayer;
    for (const n of names) {
      const e = soft.get(n);
      if (!e) errors.push(`${stem}: mesh ${n} is not in content/soft-ids.json`);
      else if (!e.meshAvailable) errors.push(`${stem}: mesh ${n} is marked meshAvailable: false`);
      else if (e.layer !== layer) errors.push(`${stem}: mesh ${n} belongs to the ${e.layer} layer`);
    }
    const there = new Set(names);
    for (const e of input.softIds) if (e.layer === layer && e.meshAvailable && !there.has(e.id)) errors.push(`${stem}: no mesh for ${e.id}`);
  }

  // --- Muscle hierarchy (plan decision 8) ---
  errors.push(...checkHierarchy());
  function checkHierarchy(): string[] {
    const out: string[] = [];
    const res = muscleHierarchySchema.safeParse(input.muscleHierarchy);
    if (!res.success) return zodLines("muscle-hierarchy.json", res.error);
    const keys = new Set<string>();
    const pathOf = new Map<string, string[]>();
    const walk = (n: MuscleHierarchyNode, path: string[]) => {
      if (keys.has(n.key)) out.push(`muscle-hierarchy.json: node key ${n.key} is used twice`);
      keys.add(n.key);
      if (n.children.length === 0 && !allowMissing) out.push(`muscle-hierarchy.json: ${n.key} has no muscles`);
      const here = [...path, n.key];
      for (const c of n.children) {
        if (typeof c !== "string") walk(c, here);
        else if (pathOf.has(c)) out.push(`muscle-hierarchy.json: ${c} appears twice`);
        else pathOf.set(c, here);
      }
    };
    res.data.forEach((n) => walk(n, []));
    for (const [id, path] of pathOf) {
      const e = soft.get(id);
      if (!e || e.kind !== "muscle") out.push(`muscle-hierarchy.json: ${id} is not a muscle in soft-ids.json`);
      else if (e.side === "right") out.push(`muscle-hierarchy.json: ${id}: list the left side only`);
      else if (!parsed.has(id)) {
        if (!allowMissing) out.push(`muscle-hierarchy.json: ${id} has no content file`);
      } else {
        const d = parsed.get(id) as MuscleFm;
        const want = d.compartment === null ? d.region : [...d.region, d.compartment];
        if (want.join(" › ") !== path.join(" › ")) out.push(`content/muscles/${id}.md: region/compartment ${want.join(" › ")} doesn't match its place in muscle-hierarchy.json (${path.join(" › ")})`);
      }
    }
    for (const e of input.softIds) {
      if (e.kind !== "muscle" || e.side === "right" || pathOf.has(e.id)) continue;
      if (parsed.has(e.id)) out.push(`muscle-hierarchy.json: ${e.id} is missing`);
      else if (!allowMissing) out.push(`muscle-hierarchy.json: ${e.id} is missing`);
    }
    // Right-side muscles must sit where their left twin does.
    for (const [id, d] of parsed) {
      if (d.kind !== "muscle" || d.side !== "right") continue;
      const left = input.opposite(id);
      const l = left ? parsed.get(left) : undefined;
      if (l && l.kind === "muscle" && (l.region.join() !== d.region.join() || l.compartment !== d.compartment))
        out.push(`content/muscles/${id}.md: region/compartment differ from ${left}`);
    }
    return out;
  }

  return { errors, warnings, files: present, expected, parsed };
}

/** The no-joint lists name real structures (run on the real soft-ids.json only). */
export function checkNoJointLists(softIds: readonly SoftIdEntry[]): string[] {
  const ids = new Set(softIds.map((e) => e.id));
  return [...LIGAMENT_NO_JOINT, ...CARTILAGE_NO_JOINT]
    .filter((key) => !ids.has(key) && !ids.has(`${key}_left`))
    .map((key) => `softValidate.ts: the no-joint list names ${key}, which isn't in content/soft-ids.json`);
}
